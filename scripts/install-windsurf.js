#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { pluginRoot } from '../hooks/lib/paths.js';
import { describeUnderTarget, installTemplates, mergeHooksByCommand, substitutePaths } from './lib/install-helpers.js';

const HOOKS_FILE_NAME = 'hooks.json';

const target = process.argv[2] ? resolve(process.cwd(), process.argv[2]) : process.cwd();
const root = pluginRoot();
const templateDir = join(root, 'windsurf');
const commandsSourceDir = join(root, 'templates', 'commands');

const report = [];

installRule();
installHooks();
installWorkflows();

process.stdout.write(`${report.join('\n')}\n`);

/**
 * Windsurf now documents `.devin/` as the preferred config directory and keeps
 * `.windsurf/` as a fallback that is read only when the `.devin/` equivalent is
 * absent. So the wrong choice isn't harmless: writing a new `.devin/hooks.json`
 * next to someone's existing `.windsurf/hooks.json` would silently shadow every
 * hook they already have. Write where their files already live; only when
 * neither exists, prefer `.devin/` if the project already has that directory and
 * `.windsurf/` (which every Windsurf version reads) if it doesn't.
 */
function locate(name) {
  const devin = join(target, '.devin', name);
  const windsurf = join(target, '.windsurf', name);
  if (existsSync(devin)) return devin;
  if (existsSync(windsurf)) return windsurf;
  return existsSync(join(target, '.devin')) ? devin : windsurf;
}

function installRule() {
  const dir = locate('rules');
  mkdirSync(dir, { recursive: true });

  const ladder = readFileSync(join(root, 'principles', 'core.md'), 'utf8').trim();
  const file = join(dir, 'pragma.md');
  const content = [
    '---',
    'trigger: always_on',
    '---',
    '',
    "<!-- Generated by pragma's install-windsurf.js from principles/core.md.",
    '     Re-run the installer after updating core.md rather than hand-editing this file. -->',
    '',
    ladder,
    '',
  ].join('\n');

  writeFileSync(file, content, 'utf8');
  report.push(`rule:      ${describeUnderTarget(file, target)}`);
}

function installHooks() {
  const file = locate(HOOKS_FILE_NAME);
  const template = substitutePaths(JSON.parse(readFileSync(join(templateDir, HOOKS_FILE_NAME), 'utf8')), root);

  const existing = readExistingHooks(file);
  if (existing === null) return; // unreadable — readExistingHooks already reported why

  mergeHooksByCommand(existing.hooks, template.hooks);

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `${JSON.stringify(existing, null, 2)}\n`, 'utf8');
  report.push(`hooks:     ${describeUnderTarget(file, target)} (post_write_code — shown to you, not the agent; see README)`);
}

/**
 * A missing file is the common case. One that isn't valid JSON is left alone
 * rather than risked — the same choice the Cursor and Antigravity installers make
 * for a hooks file they can't safely merge into.
 */
function readExistingHooks(file) {
  if (!existsSync(file)) return { hooks: {} };

  try {
    const parsed = JSON.parse(readFileSync(file, 'utf8'));
    parsed.hooks ??= {};
    return parsed;
  } catch (error) {
    report.push(`hooks:     left ${describeUnderTarget(file, target)} untouched — it isn't valid JSON`
      + ` (${error.message}). Add pragma's hook from ${join(templateDir, HOOKS_FILE_NAME)} by hand.`);
    return null;
  }
}

function installWorkflows() {
  const workflowNames = installTemplates(commandsSourceDir, locate('workflows'), root);
  report.push(`workflows: ${workflowNames.join(', ')}`);
}
