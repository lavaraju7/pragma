#!/usr/bin/env node
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { pluginRoot } from '../hooks/lib/paths.js';

const AGENTS_DIR_NAME = '.agents';
const HOOKS_FILE_NAME = 'hooks.json';
const HOOK_GROUP_NAME = 'pragma';

const target = process.argv[2] ? resolve(process.cwd(), process.argv[2]) : process.cwd();
const root = pluginRoot();
const agentsDir = join(target, AGENTS_DIR_NAME);
const templateDir = join(root, 'antigravity');
const commandsSourceDir = join(root, 'templates', 'commands');

const report = [];

installRule();
installHooks();
installWorkflows();

process.stdout.write(`${report.join('\n')}\n`);

function installRule() {
  const dir = join(agentsDir, 'rules');
  mkdirSync(dir, { recursive: true });

  const ladder = readFileSync(join(root, 'principles', 'core.md'), 'utf8').trim();
  const file = join(dir, 'pragma.md');
  const content = [
    '# Pragma',
    '',
    "<!-- Generated by pragma's install-antigravity.js from principles/core.md.",
    '     Re-run the installer after updating core.md rather than hand-editing this file. -->',
    '',
    ladder,
    '',
  ].join('\n');

  writeFileSync(file, content, 'utf8');
  report.push(`rule:      ${describeUnderTarget(file)}`);
}

/**
 * Unlike Cursor's hooks.json (event names at the top level), Antigravity's own
 * schema already namespaces by hook-*name* at the top level — so merging means
 * only ever touching pragma's own named entry and leaving every other tool's
 * entry in the file completely alone, rather than merging per-event arrays.
 */
function installHooks() {
  const file = join(agentsDir, HOOKS_FILE_NAME);
  const template = JSON.parse(readFileSync(join(templateDir, HOOKS_FILE_NAME), 'utf8'));

  const existing = readExistingHooks(file);
  if (existing === null) return; // unreadable — readExistingHooks already reported why

  existing[HOOK_GROUP_NAME] = substitutePaths(template)[HOOK_GROUP_NAME];

  mkdirSync(agentsDir, { recursive: true });
  writeFileSync(file, `${JSON.stringify(existing, null, 2)}\n`, 'utf8');
  report.push(`hooks:     ${describeUnderTarget(file)} (PostToolUse, PreInvocation, Stop — unverified, see README)`);
}

/**
 * A missing file is the common case (first install). An existing file that
 * isn't valid JSON is left alone rather than risked — the same "don't guess at
 * something unfamiliar" choice install-cursor.js makes for a hooks.json version
 * it doesn't recognise.
 */
function readExistingHooks(file) {
  if (!existsSync(file)) return {};

  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch (error) {
    report.push(`hooks:     left ${describeUnderTarget(file)} untouched — it isn't valid JSON`
      + ` (${error.message}). Add pragma's hooks from ${join(templateDir, HOOKS_FILE_NAME)} by hand.`);
    return null;
  }
}

function installWorkflows() {
  const targetDir = join(agentsDir, 'workflows');
  mkdirSync(targetDir, { recursive: true });

  const workflowNames = readdirSync(commandsSourceDir).map((name) => {
    const content = substitutePaths(readFileSync(join(commandsSourceDir, name), 'utf8'));
    writeFileSync(join(targetDir, name), content, 'utf8');
    return `/${basename(name, '.md')}`;
  });

  report.push(`workflows: ${workflowNames.join(', ')}`);
}

function substitutePaths(value) {
  const text = typeof value === 'string' ? value : JSON.stringify(value);
  const replaced = text.replaceAll('{{PRAGMA_ROOT}}', root.replaceAll('\\', '/'));
  return typeof value === 'string' ? replaced : JSON.parse(replaced);
}

/** `file` is always an absolute path already built under `target` by this script. */
function describeUnderTarget(file) {
  return file.slice(target.length + 1).replaceAll('\\', '/');
}
